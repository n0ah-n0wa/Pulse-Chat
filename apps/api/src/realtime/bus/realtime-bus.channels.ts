import { SERVER_SOCKET_EVENTS } from '@pulse-chat/shared';

/** Redis Pub/Sub channels used to fan out realtime events across instances. */
export const REALTIME_BUS_CHANNELS = {
  MESSAGE: 'pulse:realtime:message',
  REACTION: 'pulse:realtime:reaction',
  PRESENCE: 'pulse:realtime:presence',
  NOTIFICATION: 'pulse:realtime:notification',
  TYPING: 'pulse:realtime:typing',
  MEMBERSHIP: 'pulse:realtime:membership',
} as const;

export type RealtimeBusChannel = (typeof REALTIME_BUS_CHANNELS)[keyof typeof REALTIME_BUS_CHANNELS];

export const DISTRIBUTED_REALTIME_EVENTS = {
  MESSAGE_NEW: SERVER_SOCKET_EVENTS.MESSAGE_NEW,
  MESSAGE_UPDATED: SERVER_SOCKET_EVENTS.MESSAGE_UPDATED,
  MESSAGE_DELETED: SERVER_SOCKET_EVENTS.MESSAGE_DELETED,
  REACTION_ADDED: SERVER_SOCKET_EVENTS.REACTION_ADDED,
  REACTION_REMOVED: SERVER_SOCKET_EVENTS.REACTION_REMOVED,
  USER_ONLINE: SERVER_SOCKET_EVENTS.USER_ONLINE,
  USER_OFFLINE: SERVER_SOCKET_EVENTS.USER_OFFLINE,
  NOTIFICATION_NEW: SERVER_SOCKET_EVENTS.NOTIFICATION_NEW,
  TYPING_STARTED: SERVER_SOCKET_EVENTS.TYPING_STARTED,
  TYPING_STOPPED: SERVER_SOCKET_EVENTS.TYPING_STOPPED,
  MEMBER_REMOVED: 'internal:member-removed',
} as const;

export type DistributedRealtimeEvent =
  (typeof DISTRIBUTED_REALTIME_EVENTS)[keyof typeof DISTRIBUTED_REALTIME_EVENTS];

const CHANNEL_BY_EVENT: Record<DistributedRealtimeEvent, RealtimeBusChannel> = {
  [DISTRIBUTED_REALTIME_EVENTS.MESSAGE_NEW]: REALTIME_BUS_CHANNELS.MESSAGE,
  [DISTRIBUTED_REALTIME_EVENTS.MESSAGE_UPDATED]: REALTIME_BUS_CHANNELS.MESSAGE,
  [DISTRIBUTED_REALTIME_EVENTS.MESSAGE_DELETED]: REALTIME_BUS_CHANNELS.MESSAGE,
  [DISTRIBUTED_REALTIME_EVENTS.REACTION_ADDED]: REALTIME_BUS_CHANNELS.REACTION,
  [DISTRIBUTED_REALTIME_EVENTS.REACTION_REMOVED]: REALTIME_BUS_CHANNELS.REACTION,
  [DISTRIBUTED_REALTIME_EVENTS.USER_ONLINE]: REALTIME_BUS_CHANNELS.PRESENCE,
  [DISTRIBUTED_REALTIME_EVENTS.USER_OFFLINE]: REALTIME_BUS_CHANNELS.PRESENCE,
  [DISTRIBUTED_REALTIME_EVENTS.NOTIFICATION_NEW]: REALTIME_BUS_CHANNELS.NOTIFICATION,
  [DISTRIBUTED_REALTIME_EVENTS.TYPING_STARTED]: REALTIME_BUS_CHANNELS.TYPING,
  [DISTRIBUTED_REALTIME_EVENTS.TYPING_STOPPED]: REALTIME_BUS_CHANNELS.TYPING,
  [DISTRIBUTED_REALTIME_EVENTS.MEMBER_REMOVED]: REALTIME_BUS_CHANNELS.MEMBERSHIP,
};

export const ALL_REALTIME_BUS_CHANNELS: readonly RealtimeBusChannel[] = [
  REALTIME_BUS_CHANNELS.MESSAGE,
  REALTIME_BUS_CHANNELS.REACTION,
  REALTIME_BUS_CHANNELS.PRESENCE,
  REALTIME_BUS_CHANNELS.NOTIFICATION,
  REALTIME_BUS_CHANNELS.TYPING,
  REALTIME_BUS_CHANNELS.MEMBERSHIP,
];

export function channelForDistributedEvent(event: DistributedRealtimeEvent): RealtimeBusChannel {
  return CHANNEL_BY_EVENT[event];
}

/** Socket.IO room used to target a single user's local connections. */
export function userSocketRoom(userId: string): string {
  return `user:${userId}`;
}
